"""Prune a Cargo.lock to the packages that the given workspace members reach,
like cargo does after members are removed from a workspace (which it can't do
offline when the dropped packages aren't vendored).

Usage: prune-lock.py Cargo.lock MEMBER...
"""
import sys
import tomllib

lockfile, *members = sys.argv[1:]
with open(lockfile, "rb") as f:
    lock = tomllib.load(f)
packages = lock["package"]
by_name = {}
for p in packages:
    by_name.setdefault(p["name"], []).append(p)


def find(dep):
    name, *rest = dep.split(" ")
    found = by_name[name]
    if rest:
        found = [p for p in found if p["version"] == rest[0]]
    if len(found) != 1:
        sys.exit(f"{lockfile}: cannot resolve dependency {dep!r}")
    return found[0]


keep, todo = set(), [find(m) for m in members]
while todo:
    p = todo.pop()
    key = (p["name"], p["version"])
    if key in keep:
        continue
    keep.add(key)
    todo.extend(find(d) for d in p.get("dependencies", []))


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["# This file is automatically @generated by Cargo.",
       "# It is not intended for manual editing.", f"version = {lock['version']}"]
for p in packages:
    if (p["name"], p["version"]) not in keep:
        continue
    out += ["", "[[package]]", f"name = {q(p['name'])}", f"version = {q(p['version'])}"]
    for k in ("source", "checksum"):
        if k in p:
            out.append(f"{k} = {q(p[k])}")
    if p.get("dependencies"):
        out.append("dependencies = [")
        out += [f" {q(d)}," for d in p["dependencies"]]
        out.append("]")
with open(lockfile, "w") as f:
    f.write("\n".join(out) + "\n")
