"""Write the @chromium-build-deps package set: the build dependencies (DEPEND +
BDEPEND) of www-client/chromium, one atom per line.

The dependencies are evaluated by Portage exactly as for building Chromium:
the best visible www-client/chromium of this repository, with its effective
USE flags (package.use, profile masks and forces, ...). Chromium doesn't need
to be installed. For || ( ) choices, an installed alternative is kept,
otherwise the first one. Blockers and Chromium itself are left out; slot
operators are dropped.

Usage:
  chromium-build-deps.py            print the atoms
  chromium-build-deps.py --write    (re)write ${PORTAGE_CONFIGROOT}/etc/portage/sets/chromium-build-deps

--write replaces the file atomically and only after a successful evaluation;
on any failure the previous set stays as it is, so its packages stay in
@world. Run it from /etc/portage/postsync.d (see
scripts/postsync.d/chromium-build-deps) and after changing Chromium's
USE flags.
"""

import os
import re
import sys

REPO = "luke-jr-llm"


def flatten(deps, out, vardb):
    """Collect the atoms of a use_reduce(opconvert=True) result."""
    from portage.dep import Atom

    if deps and deps[0] == "||":
        alts = []
        for alt in deps[1:]:
            atoms = []
            flatten(alt if isinstance(alt, list) else [alt], atoms, vardb)
            alts.append(atoms)
        for alt in alts:
            if alt and all(vardb.match(a) for a in alt):
                out.extend(alt)
                return
        if alts:
            out.extend(alts[0])
        return
    for d in deps:
        if isinstance(d, list):
            flatten(d, out, vardb)
        elif isinstance(d, Atom) and not d.blocker:
            out.append(d)


def evaluate():
    import portage
    from portage.dep import Atom, use_reduce

    portdb = portage.db[portage.root]["porttree"].dbapi
    vardb = portage.db[portage.root]["vartree"].dbapi
    cpv = portdb.xmatch("bestmatch-visible", f"www-client/chromium::{REPO}")
    if not cpv:
        raise RuntimeError(f"no visible www-client/chromium in ::{REPO}")
    settings = portage.config(clone=portage.settings)
    settings.setcpv(cpv, mydb=portdb)
    use = settings["PORTAGE_USE"].split()
    eapi, depend, bdepend = portdb.aux_get(cpv, ["EAPI", "DEPEND", "BDEPEND"], myrepo=REPO)

    atoms = []
    for depstr in (depend, bdepend):
        flatten(use_reduce(depstr, uselist=use, eapi=eapi, opconvert=True,
                           token_class=Atom), atoms, vardb)

    lines = set()
    for a in atoms:
        if a.cp == "www-client/chromium":
            continue
        # Resolve [flag?] USE deps for Chromium's USE; drop slot operators
        # (:=, :2=, :0/1=), which only mean something inside an ebuild.
        s = str(a.evaluate_conditionals(use))
        s = re.sub(r":([^\[:/=]*)(/[^\[:=]*)?=?(?=\[|$)", r":\1", s).replace(":[", "[")
        lines.add(s[:-1] if s.endswith(":") else s)
    return sorted(lines), cpv, portage.settings["PORTAGE_CONFIGROOT"]


def main():
    write = sys.argv[1:] == ["--write"]
    if sys.argv[1:] and not write:
        sys.exit(__doc__)
    try:
        atoms, cpv, configroot = evaluate()
    except Exception as e:  # anything: Portage errors, broken repository, ...
        sys.exit(f"@chromium-build-deps: not updated: {e}")

    text = "".join(f"{a}\n" for a in atoms)
    if not write:
        sys.stdout.write(text)
        return
    path = os.path.join(configroot, "etc/portage/sets/chromium-build-deps")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path + ".tmp", "w") as f:
        f.write(f"# Build dependencies of {cpv}::{REPO} for its current USE flags.\n"
                "# Generated by scripts/chromium-build-deps.py in that repository; do not edit.\n")
        f.write(text)
    os.replace(path + ".tmp", path)
    print(f"@chromium-build-deps: {len(atoms)} packages for {cpv}", file=sys.stderr)


if __name__ == "__main__":
    main()
