#!/usr/bin/env python3
"""The tarball's stamp files (what its lastchange.py runs write) for another chromium/src
commit, as a git diff against the base tree's.

Usage: stamps.py BASE_DIR REF DEPS > stamps.diff
  BASE_DIR  a directory with the base tree's stamp files (at their paths; see STAMPS)
  REF       the new chromium/src tag or commit (e.g. refs/tags/156.0.8078.47)
  DEPS      the new commit's DEPS (for Skia's and Dawn's revisions)

The commit's hash, branch position (Cr-Commit-Position) and commit time come from Gitiles.
generated.conf lists these files as "stamp".
"""
import calendar
import difflib
import json
import os
import re
import sys
import time
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import deps  # noqa: E402

GITILES = "https://chromium.googlesource.com/chromium/src/+/"


def header(guard, define, value):
    return (f"/* Generated by lastchange.py, do not edit.*/\n\n#ifndef {guard}\n#define {guard}\n\n"
            f"#define {define} \"{value}\"\n\n#endif  // {guard}\n")


def gitiles(ref):
    for i in range(6):
        try:
            data = urllib.request.urlopen(f"{GITILES}{ref}?format=JSON", timeout=60).read()
            return json.loads(data.decode().split("\n", 1)[1])
        except OSError:
            time.sleep(5 * (i + 1))
    sys.exit(f"Gitiles: no answer for {ref}")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    base, ref, deps_file = sys.argv[1:4]
    c = gitiles(ref)
    pos = re.search(r"(?m)^Cr-Commit-Position: (\S+)$", c["message"]).group(1)
    # Gitiles shows committer times in UTC without a zone ("Mon Oct 19 20:07:21 2026").
    t = calendar.timegm(time.strptime(c["committer"]["time"], "%a %b %d %H:%M:%S %Y"))
    d = deps.load(deps_file)
    skia, dawn = d["third_party/skia"][1], d["third_party/dawn"][1]
    stamps = {
        "build/util/LASTCHANGE":
            f"LASTCHANGE={c['commit']}-{pos}\nLASTCHANGE_YEAR={time.gmtime(t).tm_year}\n",
        "build/util/LASTCHANGE.committime": str(t),
        "gpu/config/gpu_lists_version.h":
            header("GPU_CONFIG_GPU_LISTS_VERSION_H_", "GPU_LISTS_VERSION", c["commit"]),
        "skia/ext/skia_commit_hash.h":
            header("SKIA_EXT_SKIA_COMMIT_HASH_H_", "SKIA_COMMIT_HASH", skia),
        "gpu/webgpu/DAWN_VERSION": dawn,
        "gpu/webgpu/dawn_commit_hash.h":
            header("GPU_WEBGPU_DAWN_COMMIT_HASH_H_", "DAWN_COMMIT_HASH", dawn),
    }
    for path, new in stamps.items():
        old = open(os.path.join(base, path)).read()
        if old == new:
            continue
        # Check the format against the base's: only the values may differ.
        if re.sub(r"[0-9a-f]{40}|\d+", "#", old) != re.sub(r"[0-9a-f]{40}|\d+", "#", new):
            sys.exit(f"{path}: the base's format differs from what this writes:\n{old}")
        sys.stdout.write(f"diff --git a/{path} b/{path}\n")
        lines = difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                                     f"a/{path}", f"b/{path}", n=3)
        for line in lines:
            sys.stdout.write(line if line.endswith("\n") else line + "\n\\ No newline at end of file\n")


main()
